/* Meaningful state-transition checks for the synthetic cross-device workflow. */
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const context = vm.createContext({});
vm.runInContext(fs.readFileSync(path.join(__dirname,'review.js'),'utf8'),context);
const model = context.ReviewModel;
const payload={name:'Unidentified demo test',age:'',sex:'Unknown',incident:'DEMO-INC-01',triage:'unknown',location:'Training area',notes:'Synthetic workflow check'};
const starting=model.state.records.length;
model.state.offline=true;
const queued=model.submit(payload);
assert.equal(queued.status,'pending');
assert.equal(model.state.records.length,starting,'Queued reports must not reach command yet');
assert.equal(model.state.queue.length,1);
assert.throws(()=>model.sync(),/Reconnect/);
model.state.offline=false;
assert.equal(model.sync(),1);
assert.equal(model.state.queue.length,0);
assert.equal(model.state.records.length,starting+1);
assert.equal(model.sync(),0,'Repeated synchronization must not duplicate a report');
assert.equal(model.state.records.find(r=>r.id===queued.id).status,'submitted');
assert.throws(()=>model.review(queued.id,'rejected','  '),/reason/);
model.review(queued.id,'rejected','Please confirm the location.');
assert.equal(model.state.records.find(r=>r.id===queued.id).reason,'Please confirm the location.');
assert.equal(model.state.audit.length,1);
assert.throws(()=>model.review(queued.id,'verified'),/Only submitted/);
const online=model.submit({...payload,name:'Demo online test',age:'30'});
model.review(online.id,'verified');
assert.equal(model.state.records.find(r=>r.id===online.id).status,'verified');
assert.equal(online.history.length,2);
assert.throws(()=>model.submit({...payload,name:''}),/name/);
assert.throws(()=>model.submit({...payload,age:'-1'}),/age/);
assert.throws(()=>model.submit({...payload,age:'131'}),/age/);
assert.throws(()=>model.submit({...payload,incident:'INVALID'}),/incident/);
assert.throws(()=>model.submit({...payload,triage:'INVALID'}),/assessment/);
model.reset();
assert.equal(model.state.records.length,starting);
assert.equal(model.state.queue.length,0);
assert.equal(model.state.audit.length,0);
console.log('PASS: offline isolation, reconnect, repeat sync, rejection reason, approval, history, validation and reset.');
